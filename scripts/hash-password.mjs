/**
 * Turn a password into the pbkdf2$… string ADMIN_PASSWORD_HASH wants.
 *
 *   npm run admin:hash "the password"
 *
 * WHY A SCRIPT AND NOT A FORM IN THE PANEL. Changing the password has to work
 * when nobody can sign in — which is exactly the case where a form inside the
 * panel is unreachable. The credential lives in the environment (see the note in
 * lib/admin/config.ts on why it cannot live in the content store, which it
 * guards), and the environment is edited by whoever can reach the server, so
 * this belongs on the command line beside them.
 *
 * .mjs AND A COPY OF THE DERIVATION, DELIBERATELY. lib/admin/crypto.ts is
 * TypeScript, and running it here would mean a loader, a build step or tsx — a
 * dev dependency for twenty lines. The algorithm is PBKDF2-SHA256 at 210,000
 * iterations with a 16-byte salt, and the format carries its own iteration
 * count, so the two implementations agree by writing down the same four numbers
 * rather than by sharing code. If those numbers change in crypto.ts, change them
 * here — a hash generated by either still verifies, because the count travels
 * inside the string.
 */

import { pbkdf2Sync, randomBytes } from "node:crypto";

const ITERATIONS = 210_000;
const KEY_BYTES = 32;

const password = process.argv[2];

if (!password) {
  console.error(
    'Usage: npm run admin:hash "the password"\n\n' +
      "Quote it. A shell will otherwise eat spaces, and $ and ! mean something\n" +
      "to it that they do not mean to you.",
  );
  process.exit(1);
}

if (password.length < 10) {
  /* A FLOOR, NOT A POLICY. No character-class rules — they push people towards
     P@ssw0rd1 and away from four unrelated words, which is worse on both counts.
     Length is the one requirement that reliably buys entropy. */
  console.error(
    `That is ${password.length} characters. Use at least 10 — this is the only\n` +
      "credential guarding the site's published contact details.",
  );
  process.exit(1);
}

const salt = randomBytes(16);
const hash = pbkdf2Sync(password, salt, ITERATIONS, KEY_BYTES, "sha256");

const b64url = (buf) =>
  buf.toString("base64").replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");

const value = `pbkdf2$${ITERATIONS}$${b64url(salt)}$${b64url(hash)}`;

/**
 * TWO FORMS, BECAUSE A DOTENV FILE AND A HOSTING DASHBOARD DISAGREE.
 *
 * Next reads .env through dotenv-expand, which treats $NAME as a reference to
 * another variable — and this string is four fields separated by $. Pasted
 * raw into .env, "pbkdf2$210000$salt$hash" is loaded as "pbkdf2-salt-hash":
 * the iteration count and the hash expand to nothing, verifyPassword sees
 * three fields instead of four and returns false, and every sign-in fails with
 * "that email and password do not match" — a message that points at the
 * password and says nothing about the file it came from.
 *
 * A HOSTING DASHBOARD DOES NOT EXPAND ANYTHING. Vercel, Railway, Render and
 * the rest store the characters you type, so the backslashes would become part
 * of the value and break it just as thoroughly in the other direction.
 *
 * So both are printed and each says where it goes. Printing one and leaving
 * the reader to work out the other is how this gets debugged twice.
 */
console.log("\nFor a .env file — the $ must be escaped:\n");
console.log(`  ADMIN_PASSWORD_HASH=${value.replaceAll("$", "\\$")}\n`);
console.log("For a hosting dashboard (Vercel, Railway, Render) — paste as-is:\n");
console.log(`  ${value}\n`);
console.log(
  "Set one or the other, and make sure ADMIN_PASSWORD is not also set.\n",
);
